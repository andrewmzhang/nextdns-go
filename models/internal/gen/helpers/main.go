package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"text/template"
)

type Data struct {
	Name string
}

func main() {
	if len(os.Args) != 2 {
		fmt.Println("usage: go run main.go value1,value2,value3")
		os.Exit(1)
	}

	// Parse comma-separated CLI argument
	arg := os.Args[1]
	types := strings.Split(arg, ",")

	// Calculate file output
	currentFilename := os.Getenv("GOFILE")
	ext := filepath.Ext(currentFilename)
	name := strings.TrimSuffix(currentFilename, ext)
	outputFilename := name + "_gen.go"

	// Open output file
	file, err := os.Create(outputFilename)
	if err != nil {
		panic(err)
	}
	defer file.Close()

	// Template for generated code headers
	const tplHeader = `// Code generated by go generate; DO NOT EDIT.

package {{.Package}}

import "encoding/json"

`
	tmpl := template.Must(template.New("gen").Parse(tplHeader))
	data := struct {
		Package string
		Type    string
	}{
		Package: os.Getenv("GOPACKAGE"),
	}

	// Write to stdout (or a file — see below)
	if err := tmpl.Execute(file, data); err != nil {
		panic(err)
	}

	// Template for generated code body
	const tplBody = `
func (p {{.Type}}) String() string {
    type Alias {{.Type}}
	c, err := json.MarshalIndent(&struct {
		Alias
	}{
		Alias: Alias(p),
	}, "", "    ")
	if err != nil {
		return "<invalid json>"
	}
	return string(c)
}
`
	tmpl = template.Must(template.New("gen").Parse(tplBody))

	// For loop over types
	for _, typ := range types {
		data := struct {
			Package string
			Type    string
		}{
			Package: os.Getenv("GOPACKAGE"),
			Type:    strings.TrimSpace(typ),
		}

		// Write to stdout (or a file — see below)
		if err := tmpl.Execute(file, data); err != nil {
			panic(err)
		}
	}

	fmt.Println("Generated", outputFilename)
}
