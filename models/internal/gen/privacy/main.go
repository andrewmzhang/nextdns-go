package main

import (
	"context"
	"fmt"
	"log"
	"os"
	"strings"

	"github.com/andrewmzhang/nextdns-go"
)

func capitalize(s string) string {
	if s == "" {
		return s
	}
	return strings.ToUpper(s[:1]) + s[1:]
}

func dashToPascal(s string) string {
	parts := strings.Split(s, "-")
	for i, p := range parts {
		if len(p) > 0 {
			parts[i] = strings.ToUpper(p[:1]) + p[1:]
		}
	}
	return strings.Join(parts, "")
}

func main() {

	ctx := context.Background()
	client, err := nextdns.NewClient()
	if err != nil {
		log.Fatalf("Failed to create nextdns client: %v", err)
	}

	filename := "privacy_id_gen.go"
	f, err := os.Create(filename)
	if err != nil {
		log.Fatalf("Failed to create file: %v", err)
	}
	defer f.Close()

	fmt.Fprintln(f, "// Code generated by go generate; DO NOT EDIT.")
	fmt.Fprintln(f)
	fmt.Fprintln(f, "package models")
	fmt.Fprintln(f)

	privacyNatives, err := client.PrivacyNatives().List(ctx)
	if err != nil {
		log.Fatalf("Failed to fetch privacy natives: %v", err)
	}
	// fmt.Fprintln(f, "type PrivacyNativeID string")
	// fmt.Fprintln(f)
	fmt.Fprintln(f, "const (")
	for _, privacyNative := range privacyNatives {
		constName := "PrivacyNative" + capitalize(string(privacyNative.ID))
		fmt.Fprintf(
			f,
			"\t%s PrivacyNativeID = \"%s\"\n",
			constName,
			privacyNative.ID,
		)
	}
	fmt.Fprintln(f, ")")

	privacyBlocklists, err := client.PrivacyBlocklists().List(ctx)
	if err != nil {
		log.Fatalf("Failed to fetch privacy natives: %v", err)
	}
	fmt.Fprintln(f, "const (")
	for _, privacyBlocklist := range privacyBlocklists {
		constName := "PrivacyNative" + dashToPascal(string(privacyBlocklist.ID))
		fmt.Fprintf(
			f,
			"\t%s PrivacyNativeID = \"%s\"\n",
			constName,
			privacyBlocklist.ID,
		)
	}
	fmt.Fprintln(f, ")")

	fmt.Println("Generated", filename)
}
